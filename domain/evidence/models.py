"""Domain model for atomic, source-linked Evidence objects."""
from enum import Enum
from typing import Optional, Any, Dict
from pydantic import BaseModel, Field


class EvidenceSourceType(str, Enum):
    COMTRADE = "COMTRADE"
    GRAPH = "GRAPH"
    CONFIG_VALIDATOR = "CONFIG_VALIDATOR"
    EVENT_LOG = "EVENT_LOG"
    DOCUMENT = "DOCUMENT"
    INCIDENT_HISTORY = "INCIDENT_HISTORY"


class EvidenceKind(str, Enum):
    OVERCURRENT_EXCEEDED = "OVERCURRENT_EXCEEDED"
    RECORDING_TRUNCATED = "RECORDING_TRUNCATED"
    CLEARING_TIME = "CLEARING_TIME"
    CHANNEL_RMS = "CHANNEL_RMS"
    FAULT_CLASSIFICATION = "FAULT_CLASSIFICATION"
    SETTING_VERDICT = "SETTING_VERDICT"
    PHASE_INVERSION_VIOLATION = "PHASE_INVERSION_VIOLATION"
    CONFIG_VIOLATION = "CONFIG_VIOLATION"
    CONFIG_PASSED = "CONFIG_PASSED"
    TOPO_PRIMARY_RELAY = "TOPO_PRIMARY_RELAY"
    TOPO_BREAKER = "TOPO_BREAKER"
    TOPO_SENSORS = "TOPO_SENSORS"
    TOPO_MISSING = "TOPO_MISSING"
    SOE_EVENT = "SOE_EVENT"
    DOC_CHUNK = "DOC_CHUNK"
    HIST_RECORD = "HIST_RECORD"


class Evidence(BaseModel):
    """Atomic evidence fact extracted deterministically from domain tools."""
    evidence_id: str
    kind: EvidenceKind = EvidenceKind.CHANNEL_RMS
    source_type: EvidenceSourceType
    source_id: str  # e.g., "INC-2026-001.CFG", "IN_MEMORY_TOPOLOGY", "DOC-PROT-001"
    tool_name: str  # e.g., "analyze_comtrade_waveform", "query_substation_topology"
    fact: str  # Human-readable factual assertion
    structured_value: Any  # Machine-readable value (e.g. 3850.5, "CB12", True)
    unit: Optional[str] = None  # e.g. "A", "V", "ms", "Hz", "kV"
    timestamp: Optional[str] = None  # Specific millisecond timestamp if applicable
    provenance: str  # Exact channel, query, or chunk location (e.g., "Channel IC, sliding-window RMS")
    deterministic: bool = True  # True if generated by deterministic math/graph query
    metadata: Dict[str, Any] = Field(default_factory=dict)
